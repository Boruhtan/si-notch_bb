    static func frame(style: CompanionStyle, status: AgentStatus, time: TimeInterval,
                      stateAge: TimeInterval, greetingAge: TimeInterval?, reduceMotion: Bool) -> PixelCompanion {
        let time = time.isFinite ? max(0, time) : 0
        let phase = reduceMotion ? 0 : Int((time.truncatingRemainder(dividingBy: 2.0 / 3) * 6).rounded(.down)) % 4
        let working = status == .working
        let greeting = greetingAge.map { $0 >= 0 && $0 < 0.8 } ?? false
        let celebrating = status == .completed && stateAge >= 0 && stateAge < 0.7
        let jump = !reduceMotion && (greeting || celebrating) && phase % 2 == 1 ? -1 : 0
        let blink = !reduceMotion && time.truncatingRemainder(dividingBy: 5.6) > 5.43
        let happy = status == .completed || greeting
        var sprite = PixelCompanion(dimension: 40)
        var eyeX = 12, eyeY = 12 + jump, eyeDistance = 11
        var background: Character = "E", ink: Character = "H"
        var mouthY = 18 + jump
        switch style {
        case .robot:
            sprite.stamp(robot, x: 0, y: jump)
            if working && phase >= 2 { sprite.stamp("TT", x: 19, y: 3 + jump) }
        case .sprout:
            let sway = working && phase >= 2 && !reduceMotion ? 1 : 0
            sprite.stamp(leaf.joined(separator: "\n"), x: 5, y: 4 + jump + sway)
            sprite.stamp(leaf.map { String($0.reversed()) }.joined(separator: "\n"), x: 22, y: 4 + jump - sway)
            sprite.stamp("DD##DD\n.D##D.\n.D##D.\n.D##D.\n.D##D.\n.D##D.\n.D##D.", x: 17, y: 12 + jump)
            sprite.stamp(sprout, x: 0, y: jump)
            eyeY = 24 + jump; background = "F"; ink = "E"; mouthY = 30 + jump
        case .ghost:
            let y = jump
            sprite.stamp(ghost, x: 0, y: y)
            eyeX = 11; eyeY = 15 + y; eyeDistance = 13
            background = "C"; ink = "E"; mouthY = 22 + y
        case .cat:
            return PixelCat.frame(status: status, time: time, stateAge: stateAge,
                                  greetingAge: greetingAge, reduceMotion: reduceMotion)
        }
        if happy || blink || status == .ended {
            let b = String(background), e = String(ink)
            let empty = String(repeating: b, count: 5)
            let eyes = happy
                ? [empty, b + e + e + e + b, e + b + b + b + e, empty, empty]
                : [empty, empty, String(repeating: e, count: 5), empty, empty]
            for x in [eyeX, eyeX + eyeDistance] { sprite.stamp(eyes.joined(separator: "\n"), x: x, y: eyeY) }
        }
        if status == .failed || status == .waiting || status == .approval {
            let b = String(background), e = style == .robot ? "M" : "E"
            let mouth = status == .failed
                ? b + e + e + e + e + b + "\n" + e + b + b + b + b + e
                : b + b + e + e + b + b + "\n" + b + b + e + e + b + b
            sprite.stamp(mouth, x: 17, y: mouthY)
        }
        if working {
            sprite.stampKeyboard()
            sprite.stampTypingHands(style: style, phase: phase, jump: jump)
        }
        if (greeting || celebrating) && !reduceMotion {
            sprite.stamp(phase < 2 ? ".H.\nHHH\n.H." : "H.H\n.H.\nH.H", x: 35, y: 2)
        }
        if status == .approval { sprite.stamp("PP\nPP\nPP\n..\nPP", x: 36, y: 2) }
        return sprite
    }
