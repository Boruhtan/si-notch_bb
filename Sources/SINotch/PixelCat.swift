import Foundation
import SINotchCore

/// Hand-drawn 40-pixel cat for Retina compact views and larger previews.
/// The face stays still while paws type and the tail changes pose.
enum PixelCat {
    private static let portrait = """
    ........................................
    ........................................
    .......DDD....................DDD.......
    ......D###D..................D###D......
    ......DHHH#D................D####D......
    .....DHHPPH#D..............D##PP##D.....
    .....DHPPPPH#D............D##PPPP#D.....
    .....DHPPPPPH#D.DDDDDDDD.D##PPPPP#D.....
    .....DHPPPPPP##D#S#S#S##D##PPPPPP#D.....
    ....DHHPPPPP#####S#S#S######PPPPP##D....
    ....DHHPPPP#######S#S########PPPP##D....
    ....DHHHH##########################D....
    ...D#######EE##############EE#######D...
    ...D######ETEE############ETEE######D...
    ...D######EEEE############EEEE######D...
    ...D######EETE############EETE######D...
    ..D########EE#####MMMM#####EE########D..
    ...D############MMMPPMMM############D...
    ...D####PPMMMMMMMMMEEMMMMMMMMMPP####D...
    ....D##MPPMMMMMEMMMEEMMMEMMMMMPPM##D....
    .....D##MMMMMMMMEEEMMEEEMMMMMMMM##D.....
    ......DD##MMMMMMMMMMMMMMMMMMMM##DD......
    ........DDD#MMMMMMMMMMMMMMMM#DDD........
    ...........DDDDMMMMMMMMMMDDDD...........
    ...........D###MMMMMMMMMM###D...........
    ..........D###MMMMMMMMMMMM###D..........
    ..........D##MMMMMMMMMMMMMM##D..........
    .........D####MMMMMMMMMMMM####D.........
    .........D#####MMMMMMMMMM#####D.........
    .........D######MMMMMMMM######D.........
    ..........D#####MMMMMMMM#####D..........
    ...........D#####MMMMMM#####D...........
    ............D##############D............
    .............D############D.............
    ........................................
    ........................................
    ........................................
    ........................................
    ........................................
    ........................................
    """

    static func frame(status: AgentStatus, time: TimeInterval, stateAge: TimeInterval,
                      greetingAge: TimeInterval?, reduceMotion: Bool) -> PixelCompanion {
        let time = time.isFinite ? max(0, time) : 0
        let phase = reduceMotion ? 0 : Int((time.truncatingRemainder(dividingBy: 2.0 / 3) * 6).rounded(.down)) % 4
        let working = status == .working
        let greeting = greetingAge.map { $0 >= 0 && $0 < 0.8 } ?? false
        let celebrating = status == .completed && stateAge >= 0 && stateAge < 0.7
        let jump = !reduceMotion && (greeting || celebrating) && phase % 2 == 1 ? -1 : 0
        let blink = !reduceMotion && time.truncatingRemainder(dividingBy: 5.6) > 5.43
        var sprite = PixelCompanion(dimension: 40)
        let tails = [
            "..DDD..\n.DHHHD.\nDH###D.\nDH###D.\n.D###D.\n..D##D.\n..D##D.\n.D##D..\nD###D..\n###D...\nDDD....",
            "...DDD.\n..DHHHD\n.DH###D\n.DH###D\n..D###D\n..D##D.\n..D##D.\n.D##D..\nD###D..\n###D...\nDDD...."
        ]
        sprite.stamp(tails[working && phase >= 2 ? 1 : 0], x: 31, y: 22 + jump)
        sprite.stamp(portrait, x: 0, y: jump)
        if status == .completed || greeting || blink || status == .ended {
            let eyes = status == .completed || greeting
                ? "####\n#EE#\nE##E\n####\n####"
                : "####\n####\nEEEE\n####\n####"
            for x in [10, 26] { sprite.stamp(eyes, x: x, y: 12 + jump) }
        }
        if status == .failed {
            sprite.stamp("MMMMMMMMMM\nMMMMMMMMMM\nMMMEEEEMMM\nMMEMMMMEMM", x: 15, y: 18 + jump)
        }
        if working {
            sprite.stampKeyboard()
            sprite.stampTypingHands(style: .cat, phase: phase, jump: jump)
        } else {
            sprite.stamp("DHHHHHD....DHHHHHD\nD#####D....D#####D\n.DDDDD......DDDDD.", x: 11, y: 33 + jump)
        }
        if (greeting || celebrating) && !reduceMotion {
            sprite.stamp(phase < 2 ? "..H..\n..H..\nHHHHH\n..H..\n..H.." : "H...H\n.H.H.\n..H..\n.H.H.\nH...H", x: 34, y: 2)
        }
        if status == .approval { sprite.stamp("HH\nHH\nHH\n..\nHH", x: 36, y: 3) }
        return sprite
    }
}
